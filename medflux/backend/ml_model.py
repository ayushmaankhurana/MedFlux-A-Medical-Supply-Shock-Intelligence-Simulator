import networkx as nx

def simulate(G, steps=30):
    """
    Run a basic inventory simulation over a network.

    Args:
        G: networkx.DiGraph
        steps: number of timesteps

    Returns:
        history: list of dicts, each dict = {node_id: inventory}
    """
    history = []

    for t in range(steps):
        # Update inventory for each node
        for node in G.nodes:
            inv = G.nodes[node]["inventory"]
            demand = G.nodes[node].get("demand", 0)
            # Inventory consumed by demand
            inv = max(inv - demand, 0)
            G.nodes[node]["inventory"] = inv

            # Optional: propagate inventory downstream if edges exist
            for succ in G.successors(node):
                edge_capacity = G.edges[node, succ].get("capacity", 100)
                # Send min of node inventory or edge capacity
                transfer = min(inv, edge_capacity)
                G.nodes[succ]["inventory"] += transfer
                G.nodes[node]["inventory"] -= transfer

        # Record snapshot of current inventory
        history.append({n: G.nodes[n]["inventory"] for n in G.nodes})

    return history


def inject_shock(G, node_id, magnitude=0.5):
    """
    Apply a shock to a node by reducing its inventory.

    Args:
        G: networkx.DiGraph
        node_id: str
        magnitude: float (0-1), fraction to reduce
    """
    if node_id in G.nodes:
        G.nodes[node_id]["inventory"] *= (1 - magnitude)
        print(f"Injected shock at {node_id}: new inventory = {G.nodes[node_id]['inventory']}")


def predict_from_sim(history, node_id):
    """
    Optional: simple recovery metric.
    Returns peak shortage for a node.
    """
    inv_list = [step[node_id] for step in history]
    peak = max(inv_list)
    min_inv = min(inv_list)
    shortage = peak - min_inv
    return shortage

