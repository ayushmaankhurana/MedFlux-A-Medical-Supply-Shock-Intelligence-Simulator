import networkx as nx

def load_network(data):
    """
    Load a network from JSON into a NetworkX DiGraph.

    Args:
        data: dict
            {
                "nodes": [
                    {"id":"S1", "type":"supplier", "inventory":100, "demand":0},
                    ...
                ],
                "edges": [
                    {"source":"S1","target":"M1","capacity":100, "transport_time":2},
                    ...
                ]
            }

    Returns:
        G: networkx.DiGraph
    """
    G = nx.DiGraph()

    # Add nodes
    for node in data.get("nodes", []):
        G.add_node(
            node["id"],
            type=node.get("type", "unknown"),
            inventory=node.get("inventory", 0),
            demand=node.get("demand", 0),
            lead_time=node.get("lead_time", 1)  # optional attribute
        )

    # Add edges
    for edge in data.get("edges", []):
        G.add_edge(
            edge["source"],
            edge["target"],
            capacity=edge.get("capacity", 100),
            transport_time=edge.get("transport_time", 1)  # optional
        )

    print(f"Loaded network with {G.number_of_nodes()} nodes and {G.number_of_edges()} edges.")
    return G

