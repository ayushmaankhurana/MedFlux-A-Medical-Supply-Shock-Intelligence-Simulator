def recommend_buffers(G, total_buffer=300):
    import networkx as nx
    centrality = nx.betweenness_centrality(G)
    total_centrality = sum(centrality.values())
    recommended = {}
    for node in G.nodes:
        weight = centrality[node] / total_centrality
        recommended[node] = total_buffer * weight
    return recommended

